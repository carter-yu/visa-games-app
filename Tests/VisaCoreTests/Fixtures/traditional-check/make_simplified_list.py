#!/usr/bin/env python3
"""Writes simplified-only.txt: the CJK characters OpenCC treats as Simplified-only (weekly-report design §6.3).

A character is listed when OpenCC's Simplified → Traditional (HK) mapping changes it and its own
Traditional → Simplified mapping keeps it: the rule of `visa-games-design/weekly-report/mockups/
check_traditional.py`. HK glyph variants (t2hk) are not listed: the app's game titles keep their own
characters (e.g. 搵). The written-Cantonese particles 吓 and 晒 are allowed (§6.3) and left out.

Needs the python3 `opencc` module (generated with the pip package `opencc-python-reimplemented` 0.1.7,
which ships the OpenCC dictionaries). Deterministic for one dictionary version:

    cd Tests/VisaCoreTests/Fixtures/traditional-check
    python3 make_simplified_list.py > simplified-only.txt
"""

import importlib.metadata
import sys

import opencc


def opencc_version():
    for name in ("opencc-python-reimplemented", "opencc", "OpenCC"):
        try:
            return "%s %s" % (name, importlib.metadata.version(name))
        except importlib.metadata.PackageNotFoundError:
            continue
    return "opencc (version unknown)"

ALLOWED = {"吓": "試吓 (Activity.swift 「數吓有幾多架」)", "晒": "點晒 (Activity.swift 「點晒啲車」)"}
RANGES = [(0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF)]  # check_traditional.is_cjk
PER_LINE = 64


def main():
    s2hk = opencc.OpenCC("s2hk")
    t2s = opencc.OpenCC("t2s")
    found = []
    for low, high in RANGES:
        for code in range(low, high + 1):
            ch = chr(code)
            if ch in ALLOWED:
                continue
            if s2hk.convert(ch) != ch and t2s.convert(ch) == ch:
                found.append(ch)
    out = sys.stdout
    out.write("# Simplified-only CJK characters (OpenCC s2hk changes them, t2s keeps them): %d characters.\n"
              % len(found))
    out.write("# Generated by make_simplified_list.py with %s; 吓 and 晒 are allowed (design §6.3).\n"
              % opencc_version())
    out.write("# Lines starting with # are comments; every other character is one entry.\n")
    for start in range(0, len(found), PER_LINE):
        out.write("".join(found[start:start + PER_LINE]) + "\n")


if __name__ == "__main__":
    main()
