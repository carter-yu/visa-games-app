#!/usr/bin/env python3
"""Generate the English-only LWT letter guide data from the locked letter spec."""
import argparse
import json
import os
from guidance_spec_to_swift import ROOT, COPY_LINES, PARENT, fail, lit, num, colour, point

LETTERS = "abcdegkou"


def line(d, where):
    if not isinstance(d, dict) or not d.get("en"):
        fail(where + ": missing English copy line")
    return "TapCountGuideLine(zh: %s, zhSub: %s, en: %s, enSub: %s)" % (
        lit(d.get("zh", "")), lit(d.get("zhSub", "")), lit(d["en"]), lit(d.get("enSub", "")))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", default=os.path.join(ROOT, "docs", "letter-tap-guidance-spec.json"))
    ap.add_argument("--out", default=os.path.join(ROOT, "Sources", "VisaCore", "LetterGuideData.swift"))
    args = ap.parse_args()
    spec = json.load(open(args.source, encoding="utf-8"))
    entries = []
    for letter in LETTERS:
        d = spec.get("letters", {}).get(letter) or fail("missing letter " + letter)
        beats = []
        for i, b in enumerate(d.get("beats", [])):
            where = "letter %s beat %d" % (letter, i)
            until = b["until"]
            if isinstance(until, (int, float)):
                if float(until) != 1.0:
                    fail(where + ": numeric until must be 1.0")
                until_s = "nil"
            else:
                until_s = point(until, where)
            if b.get("seconds", 0) <= 0:
                fail(where + ": seconds")
            beats.append("NumeralGuideBeatSpec(stroke: %d, until: %s, seconds: %s, line: %s)" % (
                b["stroke"], until_s, num(b["seconds"]), line(b, where)))
        if not beats:
            fail("letter %s: no beats" % letter)
        cues = []
        for i, c in enumerate(d.get("cues", [])):
            where = "letter %s cue %d" % (letter, i)
            if c.get("sign") not in ("stop", "ahead"):
                fail(where + ": sign")
            x, y = c["signAt"]
            cues.append("NumeralGuideCueSpec(stroke: %d, point: %s, sign: .%s, signAt: LineMatchPoint(x: %s, y: %s), line: %s)" % (
                c["stroke"], point(c, where), c["sign"], num(x), num(y), line(c, where)))
        hop = d.get("hop")
        last = d.get("lastStroke")
        side = d.get("hopArcSide")
        if side not in (None, "left", "right", "up", "down"):
            fail("letter %s: hopArcSide" % letter)
        entries.append("        case %s: return NumeralGuideSpec(numeral: 0, beats: [\n                %s\n            ], merge: %s, cues: [%s], hop: %s, hopSide: %s, lastStroke: %s)" % (
            lit(letter), ",\n                ".join(beats), line(d.get("merge"), "letter %s merge" % letter),
            ", ".join(cues), line(hop, "letter %s hop" % letter) if hop else "nil", "." + side if side else "nil",
            line(last, "letter %s lastStroke" % letter) if last else "nil"))
    c = spec.get("copy") or fail("missing copy")
    copy = []
    for k in COPY_LINES:
        copy.append("%s: %s" % (k, line(c.get(k), "copy." + k)))
    p = c.get("parent") or fail("missing parent copy")
    for k in PARENT:
        if not p.get(k):
            fail("missing parent copy." + k)
    parent = "TapCountGuideParentCopy(%s)" % ", ".join("%s: %s" % (k, lit(p[k])) for k in PARENT)
    st = spec["styles"]
    b = st["letterBoard"]
    keys = ("laneScale", "carScale", "noseUnits", "chevScale", "laneDotSpacing", "stopSignScale", "aheadSignScale")
    style = "LetterBoardGuideStyle(%s)" % ", ".join("%s: %s" % (k, num(b[k])) for k in keys)
    r, beam, hop, ring, glow = (st[k] for k in ("route", "beam", "hopArc", "stallRing", "litGlow"))
    styles = ("TapCountGuideStyles(routeGlow: %s, routeGlowWidth: %s, routeCore: %s, routeCoreWidth: %s, routeDash: [%s], "
              "beamOuter: %s, beamOuterWidth: %s, beamInner: %s, beamInnerWidth: %s, beamInnerOpacity: %s, "
              "hopArc: %s, hopArcWidth: %s, hopArcDash: [%s], fadedStrokeOpacity: %s, "
              "stallRingRadius: %s, stallRingFill: %s, stallRingStroke: %s, "
              "litGlow: %s, litGlowWidth: %s, litGlowOpacity: %s, litGlowSeconds: %s)") % (
        colour(r["glow"]), num(r["glowWidth"]), colour(r["core"]), num(r["coreWidth"]),
        ", ".join(num(x) for x in r["dash"]), colour(beam["outer"]), num(beam["outerWidth"]),
        colour(beam["inner"]), num(beam["innerWidth"]), num(beam.get("innerOpacity", 1)),
        colour(hop["stroke"]), num(hop["width"]), ", ".join(num(x) for x in hop["dash"]),
        num(st["fadedStrokeOpacity"]), num(ring["radius"]), colour(ring["fill"]), colour(ring["stroke"]),
        colour(glow["color"]), num(glow["width"]), num(glow["opacity"]), num(glow["seconds"]))
    out = """// GENERATED by scripts/letter_guidance_spec_to_swift.py from docs/letter-tap-guidance-spec.json.
// Do not edit by hand.
import Foundation

public enum LetterGuideData {
    public static func letter(_ letter: Character) -> NumeralGuideSpec? {
        switch letter {
%s
        default: return nil
        }
    }
    public static let board = %s
    public static let styles = %s
    public static let copy = TapCountGuideCopy(%s,
        stopWordZh: %s, stopWordEn: %s, parent: %s)
    public static let timing = TapCountGuideData.timing
    public static func level(_ level: TapCountGuidanceLevel) -> TapCountGuideLevelSpec { TapCountGuideData.level(level) }
    public static let cleanInARow = TapCountGuideData.cleanInARow
}
""" % ("\n".join(entries), style, styles, ", ".join(copy), lit(c["stopWord"].get("zh", "")), lit(c["stopWord"]["en"]), parent)
    open(args.out, "w", encoding="utf-8").write(out)
    print("wrote", os.path.relpath(args.out, ROOT))


if __name__ == "__main__":
    main()
