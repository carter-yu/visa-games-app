#!/usr/bin/env python3
"""Convert the 畫線畫形 art source into Swift `CanvasArtwork` data (v0.25.0, ADR 0014).

Source: scripts/art/shape-trace-source.svg — elements copied verbatim from the approved Opus
mockups in visa-games-design/shape-trace/mockups (see the comment at the top of that file).
Output: Sources/VisaCore/ShapeTraceArt.swift (generated; do not edit by hand).

Reuses the 連一連 converter (scripts/svg_to_canvasart.py): same style inheritance, same loud
failure on anything it does not understand.

Usage: python3 scripts/svg_to_shapetraceart.py [--source FILE] [--out FILE]
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import svg_to_canvasart as base  # noqa: E402

# (swift name, svg id, minX, minY, width, height). The art's origin (0, 0) is the anchor the app
# places on a stage point: marker centre, vehicle ground centre / centre, hook cable end.
CENTRED = [
    ("go", "go", -31, -31, 62, 62),
    ("end", "end", -31, -31, 62, 62),
    ("tick", "tick", -33, -33, 66, 66),
    ("tickSmall", "tick-s", -23, -23, 46, 46),
    ("endRing", "end-ring", -21, -21, 42, 42),
    ("stopSign", "stop-sign", -34, -34, 68, 68),
    ("fireEngine", "fire-engine", -116, -132, 232, 136),
    ("taxi", "taxi", -92, -96, 186, 100),
    ("paintCar", "paint-car", -53, -33, 106, 66),
    ("craneHook", "crane-hook", -24, -4, 48, 56),
    ("pine", "pine", -61, -153, 122, 180),
    ("snowArms", "snow-arms", -164, -72, 328, 50),
]
# Stage-sized scenery: 1280 × 720, origin top-left.
STAGE = [
    ("fireStation", "fire-station"),
    ("hill", "hill"),
    ("craneBoom", "crane-boom"),
    ("craneTruck", "crane-truck"),
    ("craneBox", "crane-box"),
    ("castleTowers", "castle-towers"),
    ("castleFacade", "castle-facade"),
    ("snowGround", "snow-ground"),
    ("church", "church"),
]


def render(arts):
    lines = [
        "// GENERATED by scripts/svg_to_shapetraceart.py from scripts/art/shape-trace-source.svg",
        "// (copied from the approved Opus mockups, visa-games-design/shape-trace/mockups 01–04).",
        "// Do not edit by hand: change the SVG, re-run the script, and commit both.",
        "import Foundation",
        "",
        "/// 畫線畫形 / Lines & Shapes vector art (design §2.8, ADR 0014). Original art only.",
        "public enum ShapeTraceArt {",
        "    /// Every artwork. Names are `shapeTrace.<name>`.",
        "    public static let all: [CanvasArtwork] = [",
        "        " + ", ".join(name for name, _, _, _ in arts),
        "    ]",
        "",
        "    /// Where the art's anchor sits inside its box (marker centre, vehicle ground centre,",
        "    /// hook cable end). Stage-sized scenery anchors at its top-left corner.",
        "    public static func anchor(_ artwork: CanvasArtwork) -> LineMatchPoint {",
        "        anchors[artwork.name] ?? LineMatchPoint(x: 0, y: 0)",
        "    }",
        "",
        "    static let anchors: [String: LineMatchPoint] = [",
    ]
    anchor_lines = []
    for name, ident, min_x, min_y, width, height in CENTRED:
        anchor_lines.append('        "shapeTrace.%s": LineMatchPoint(x: %s, y: %s)' % (name, base.fmt(-min_x), base.fmt(-min_y)))
    lines.append(",\n".join(anchor_lines))
    lines += ["    ]", ""]
    for name, (width, height), elements in [(a[0], (a[1], a[2]), a[3]) for a in arts]:
        lines.append("    public static let %s = CanvasArtwork(name: \"shapeTrace.%s\", width: %s, height: %s, elements: ["
                     % (name, name, base.fmt(width), base.fmt(height)))
        lines.append(",\n".join("        " + base.swift_element(el) for el in elements))
        lines.append("    ])")
        lines.append("")
    lines += ["}", ""]
    return "\n".join(lines)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", default=os.path.join(here, "art", "shape-trace-source.svg"))
    parser.add_argument("--out", default=os.path.join(here, "..", "Sources", "VisaCore", "ShapeTraceArt.swift"))
    args = parser.parse_args()
    by_id, clips = base.load(args.source)
    arts = []
    for name, ident, min_x, min_y, width, height in CENTRED:
        node = by_id.get(ident)
        if node is None:
            raise base.ConvertError("art source has no #%s" % ident)
        arts.append((name, width, height, base.convert(node, clips, -min_x, -min_y)))
    for name, ident in STAGE:
        node = by_id.get(ident)
        if node is None:
            raise base.ConvertError("art source has no #%s" % ident)
        arts.append((name, 1280, 720, base.convert(node, clips)))
    with open(args.out, "w", encoding="utf-8") as handle:
        handle.write(render(arts))
    print("wrote %s: %d artworks, %d elements" % (os.path.relpath(args.out), len(arts), sum(len(a[3]) for a in arts)))


if __name__ == "__main__":
    try:
        main()
    except base.ConvertError as error:
        sys.stderr.write("svg_to_shapetraceart: %s\n" % error)
        sys.exit(1)
