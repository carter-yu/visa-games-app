    /// Words of label `id` with `{slots}` filled in one pass; an unknown id gives empty words.
    public static func text(_ id: String, _ values: [String: WeeklyWords] = [:]) -> WeeklyWords {
        guard let words = table[id] else { return WeeklyWords("", "") }
        var zhValues: [String: String] = [:]
        var enValues: [String: String] = [:]
        for (key, value) in values {
            zhValues[key] = value.zh
            enValues[key] = value.en
        }
        var missing: [String] = []
        let zh = WeeklyFormat.fill(words.zh, zhValues, missing: &missing)
        let en = WeeklyFormat.fill(words.en, enValues, missing: &missing)
        return WeeklyWords(zh, en)
    }

    /// The same text in both languages (numbers, ids, times).
    public static func same(_ text: String) -> WeeklyWords {
        WeeklyWords(text, text)
    }

    public static func number(_ value: Int) -> WeeklyWords {
        same(String(value))
    }

    /// Glossary entries with their numbers filled in (5 rounds, 20 points).
    public static func glossaryEntries() -> [WeeklyGlossaryEntry] {
        var values: [String: String] = [:]
        values["min"] = String(WeeklyRanking.minimumRounds)
        values["points"] = String(WeeklyReportHTML.samePoints)
        var out: [WeeklyGlossaryEntry] = []
        for entry in glossary {
            var missing: [String] = []
            let zh = WeeklyFormat.fill(entry.zh, values, missing: &missing)
            let en = WeeklyFormat.fill(entry.en, values, missing: &missing)
            out.append(WeeklyGlossaryEntry(term: entry.term, zh: zh, en: en))
        }
        return out
    }
